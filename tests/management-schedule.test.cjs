test('weekly reconciliation preserves known early work and distributes only the remaining actual hours', () => {
  const f = settlementFixture(), before = structuredClone(f.state), input = settlementInput()
  const rows = getWeekEffortRows(f.state, 'person', input.week)
  assert.equal(rows.find(row => row.effort.id === 'early-hours').known, true)
  assert.equal(rows.find(row => row.effort.id === 'front-hours').known, true)
  const preview = previewWeekEffortSettlement(f.state, input), command = prepareWeekEffortSettlement(f.state, input)
  assert.deepEqual(f.state, before)
  assert.equal(preview.previousHours, 56)
  assert.equal(preview.knownHours, 16)
  assert.equal(preview.allocatedHours, 24)
  f.apply(command)
  assert.deepEqual(f.state.efforts.map(row => row.hours), [14.4, 9.6, 16])
  assert.deepEqual(f.state.efforts.map(row => row.hoursSource), ['allocated', 'allocated', 'reported'])
  assert.deepEqual(f.state.efforts.slice(0, 2).map(row => row.allocationWeight), [24, 16])
  assert.deepEqual(f.state.plans, before.plans)
  assert.deepEqual(f.state.tasks, before.tasks)
  assert.deepEqual(f.state.requirements, before.requirements)
  assert.equal(getWeekSummary(f.state, input.week).actualHours, 40)
  assert.equal(getScopeSchedule(f.state, ['early-task']).status, 'early')
  assert.equal(getRequirementSchedule(f.state, 'requirement').allocatedHours, 24)
  assert.equal(f.state.weekActuals[0].basis, 'confirmed')
  f.apply(prepareWeekEffortSettlement(f.state, input))
  assert.equal(f.state.weekActuals.length, 1)
  assert.equal(f.state.efforts.length, 3)
  assert.deepEqual(f.state.efforts.map(row => row.hours), [14.4, 9.6, 16])
})

test('rounding uses exact four-decimal totals and does not cap genuine overtime at standard capacity', () => {
  const f = settlementFixture()
  for (const target of [40.0001, 48.1234, 60, 16, 0]) {
    const input = settlementInput({ totalHours: target, known: [{ key: 'effort:early-hours', hours: target ? 16 : 0 }] })
    const preview = previewWeekEffortSettlement(f.state, input)
    assert.equal(preview.rows.reduce((sum, row) => sum + Math.round(row.hours * 10000), 0), Math.round(target * 10000))
    assert.equal(preview.rows.find(row => row.key === 'effort:early-hours').hours, target ? 16 : 0)
    assert(preview.rows.every(row => row.hours >= 0))
  }
})

