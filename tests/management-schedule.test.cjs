const settlementInput = (extra = {}) => ({ personId: 'person', week: '2026-11-02', totalHours: 40, known: [{ key: 'effort:early-hours', hours: 16 }], ...extra })

test('legacy 8h, 8h and 24h actual records default to preserved hours instead of an unknown 0h subtotal', () => {
  const f = fixture()
  f.save('tasks', { id: 'backend', requirementId: 'requirement', name: '后端', role: 'backend', stage: 'backend', ownerId: 'person' })
  f.save('requirements', { id: 'recognition', projectId: 'project', versionId: 'version', title: '订单四种识别' })
  f.save('tasks', { id: 'recognition-task', requirementId: 'recognition', name: '后端', role: 'backend', stage: 'backend', ownerId: 'person' })
  f.plan({ id: 'recognition-plan', taskIds: ['recognition-task'], role: 'backend', stage: 'backend', week: '2026-11-02', plannedHours: 24, outcome: 'done', completedWeek: '2026-11-02' })
  for (const [id, role, taskId, hours, planId] of [['front-hours', 'frontend', 'frontend', 8, ''], ['back-hours', 'backend', 'backend', 8, ''], ['recognition-hours', 'backend', 'recognition-task', 24, 'recognition-plan']]) {
    f.save('efforts', { id, projectId: 'project', versionId: 'version', personId: 'person', role, stage: role, taskIds: [taskId], week: '2026-11-02', hours, planId })
  }
  const before = structuredClone(f.state), rows = getWeekEffortRows(f.state, 'person', '2026-11-02')
  assert.equal(rows.length, 3)
  assert(rows.every(row => row.known && !row.early && row.effort.hoursSource === undefined))
  const input = settlementInput({ totalHours: getWeekEffortDefaultHours(f.state, 'person', '2026-11-02'), known: rows.filter(row => row.known).map(row => ({ key: row.key, hours: row.effort.hours })) })
  const preview = previewWeekEffortSettlement(f.state, input)
  assert.equal(preview.knownHours, 40)
  assert.equal(preview.allocatedHours, 0)
  assert.equal(preview.totalHours, 40)
  assert.deepEqual(preview.rows.map(row => row.hours), [8, 8, 24])
  assert.deepEqual(f.state, before)
  f.apply(prepareWeekEffortSettlement(f.state, input))
  assert.deepEqual(f.state.efforts.map(row => row.hours), [8, 8, 24])
  assert(f.state.efforts.every(row => row.hoursSource === 'reported'))
  assert.equal(getWeekSummary(f.state, input.week).actualHours, 40)
})

