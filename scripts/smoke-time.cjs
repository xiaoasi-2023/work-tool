const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')

const url = process.env.WORKBENCH_WEB_URL || 'http://127.0.0.1:5173'
const output = path.resolve(__dirname, '../output/playwright')
async function select(page, label, option, filter) {
  const wrapper = page.locator('.el-select').filter({ has: page.getByRole('combobox', { name: label, exact: true }) })
  await wrapper.locator('.el-select__wrapper').click()
  if (filter) await page.getByRole('combobox', { name: label, exact: true }).fill(filter)
  await page.getByRole('option', { name: option, exact: true }).click()
}
async function open(page) {
  await page.goto(url)
  await page.locator('.tool-title').filter({ hasText: '时间戳' }).click()
  await page.getByRole('heading', { name: '时间戳工作台' }).waitFor()
}
async function main() {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const errors = []
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    page.setDefaultTimeout(15000)
    page.on('pageerror', error => errors.push(error.message))
    await open(page)
    await select(page, '时区', 'Asia/Shanghai', 'Shanghai')
    await page.getByRole('textbox', { name: 'Unix 时间戳', exact: true }).fill('0')
    await page.getByRole('button', { name: '转换', exact: true }).first().click()
    await page.locator('.conversion-results').waitFor()
    assert.match(await page.locator('.conversion-results').innerText(), /1970-01-01 08:00:00 \+08:00/)
    await select(page, '时间戳单位', '纳秒 (ns)')
    await page.getByRole('textbox', { name: 'Unix 时间戳', exact: true }).fill('1793419200123456789')
    await page.getByRole('button', { name: '转换', exact: true }).first().click()
    assert.match(await page.locator('.conversion-results').innerText(), /2026-10-31T04:00:00.123456789Z/)
    assert.match(await page.locator('.conversion-results').innerText(), /1793419200123456789/)
    await select(page, '时区', 'UTC', 'UTC')
    assert.match(await page.locator('.conversion-results').innerText(), /2026-10-31 04:00:00.123456789 \+00:00/)
    await page.getByRole('textbox', { name: '日期时间', exact: true }).fill('2026-02-30 12:00:00')
    await page.getByRole('button', { name: '转换', exact: true }).nth(1).click()
    await page.locator('.el-alert--error').waitFor()
    await page.getByRole('textbox', { name: '日期时间', exact: true }).fill('2026-10-31T12:00:00+08:00')
    await page.getByRole('button', { name: '转换', exact: true }).nth(1).click()
    assert.match(await page.locator('.conversion-results').innerText(), /2026-10-31T04:00:00.000Z/)
    await page.getByRole('button', { name: '暂停时钟', exact: true }).click()
    await page.getByRole('button', { name: '继续时钟', exact: true }).waitFor()
    await page.getByRole('button', { name: '本月末', exact: true }).click()
    assert.match(await page.locator('.conversion-results').innerText(), /23:59:59.999999999/)
    const savedDate = await page.getByRole('textbox', { name: '日期时间', exact: true }).inputValue()
    await page.screenshot({ path: path.join(output, 'time-convert-desktop.png'), animations: 'disabled' })
    await page.getByRole('button', { name: '批量转换', exact: true }).first().click()
    await select(page, '批量输出格式', 'UTC / ISO 8601')
    await page.getByRole('textbox', { name: '批量时间输入', exact: true }).fill('0\n1793419200123456789\n\nnot-a-date\n2026-10-31T12:00:00+08:00')
    await page.getByRole('button', { name: '批量转换', exact: true }).last().click()
    assert.equal(await page.locator('.time-batch-table tbody tr').count(), 4)
    assert.equal(await page.locator('.time-batch-table tr.failed').count(), 1)
    assert.match(await page.locator('.time-batch-table').innerText(), /2026-10-31T04:00:00.123456789Z/)
    const downloaded = page.waitForEvent('download')
    await page.getByRole('button', { name: '下载批量结果', exact: true }).click()
    const file = await downloaded
    assert.match(await fs.readFile(await file.path(), 'utf8'), /4\tnot-a-date\t错误/)
    await page.screenshot({ path: path.join(output, 'time-batch-desktop.png'), animations: 'disabled' })
    await select(page, '批量输出格式', '纳秒 (ns)')
    assert.equal(await page.locator('.time-batch-table').count(), 0)
    await page.getByRole('button', { name: '日期计算', exact: true }).click()
    await page.getByRole('textbox', { name: '计算基准时间', exact: true }).fill('2026-01-31 12:00:00')
    await select(page, '日期增减单位', '月')
    await page.getByRole('button', { name: '计算日期', exact: true }).click()
    assert.match(await page.locator('.time-calculations > section').first().innerText(), /2026-02-28 12:00:00/)
    await page.getByRole('textbox', { name: '时间差开始时间', exact: true }).fill('2026-10-31T00:00:00Z')
    await page.getByRole('textbox', { name: '时间差结束时间', exact: true }).fill('2026-11-01T01:01:01.001Z')
    await page.getByRole('button', { name: '计算时间差', exact: true }).click()
    assert.match(await page.locator('.time-calculations > section').nth(1).innerText(), /1 天 1 小时 1 分 1 秒 1 毫秒/)
    await page.getByRole('button', { name: '交换起止时间', exact: true }).click()
    await page.getByRole('button', { name: '计算时间差', exact: true }).click()
    assert.match(await page.locator('.time-calculations > section').nth(1).innerText(), /-1 天/)
    await page.screenshot({ path: path.join(output, 'time-calculation-desktop.png'), animations: 'disabled' })
    await page.reload()
    await page.locator('.tool-title').filter({ hasText: '时间戳' }).click()
    assert.equal(await page.getByRole('textbox', { name: '日期时间', exact: true }).inputValue(), savedDate)
    await page.getByRole('button', { name: '日期计算', exact: true }).click()
    assert.equal(await page.getByRole('textbox', { name: '计算基准时间', exact: true }).inputValue(), '2026-01-31 12:00:00')
    await page.close()
    for (const viewport of [{ width: 390, height: 844 }, { width: 900, height: 640 }]) {
      const small = await browser.newPage({ viewport }); small.setDefaultTimeout(15000)
      small.on('pageerror', error => errors.push(error.message))
      await open(small)
      await small.getByRole('textbox', { name: 'Unix 时间戳', exact: true }).fill('0')
      await small.getByRole('button', { name: '转换', exact: true }).first().click()
      for (const name of ['时间转换', '批量转换', '日期计算']) {
        await small.locator('.time-tabs').getByRole('button', { name, exact: true }).click()
        assert.equal(await small.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
        assert.equal(await small.locator('main').evaluate(node => node.scrollWidth > node.clientWidth), false)
        await small.screenshot({ path: path.join(output, `time-${name}-${viewport.width}.png`), animations: 'disabled' })
      }
      await small.locator('.sidebar-bottom .nav-item').filter({ hasText: '设置' }).click()
      await small.locator('.el-radio-button').filter({ hasText: '深色' }).click()
      await small.waitForFunction(() => document.documentElement.dataset.theme === 'dark')
      await small.getByRole('button', { name: '全部工具', exact: false }).first().click()
      await small.locator('.tool-title').filter({ hasText: '时间戳' }).click()
      await small.getByRole('button', { name: '今日零点', exact: true }).click()
      await small.screenshot({ path: path.join(output, `time-dark-${viewport.width}.png`), animations: 'disabled' })
      await small.close()
    }
    assert.deepEqual(errors, [])
    console.log('Time smoke passed: nanoseconds, zones, strict dates, shortcuts, batch errors/export, calendar arithmetic, differences, drafts and responsive dark/light layouts.')
  } catch (error) {
    for (const context of browser.contexts()) for (const page of context.pages()) await page.screenshot({ path: path.join(output, 'time-failure.png') }).catch(() => {})
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
