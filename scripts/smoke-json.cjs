      await small.getByRole('button', { name: '全部工具', exact: false }).first().click()
      await small.locator('.tool-title').filter({ hasText: 'JSON' }).click()
      await waitText(small, '处理结果', '90071992547409931234')
      await small.screenshot({ path: path.join(output, `json-dark-${viewport.width}.png`), animations: 'disabled' })
