    await page.locator('.cm-search [name="replaceAll"]').click()
    await waitText(page, '处理结果', 'replaced')
    await page.getByRole('button', { name: '撤销', exact: true }).click()
    await waitText(page, '处理结果', 'old')
    await page.getByRole('button', { name: '重做', exact: true }).click()
    await waitText(page, '处理结果', 'replaced')
    await page.locator('.cm-search [name="close"]').click()
    await page.getByRole('tab', { name: '结构', exact: true }).click()
    await page.getByRole('button', { name: '编辑 name', exact: true }).click()
    await page.getByRole('textbox', { name: '字段名称', exact: true }).fill('title')
    await page.getByRole('textbox', { name: '字段值', exact: true }).fill('renamed')
    await page.getByRole('button', { name: '应用修改', exact: true }).click()
