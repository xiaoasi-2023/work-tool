const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')

const url = process.env.WORKBENCH_WEB_URL || 'http://127.0.0.1:5173'
const output = path.resolve(__dirname, '../output/playwright')
async function checkbox(page, name, checked) {
  const input = page.getByRole('checkbox', { name, exact: true })
  if (await input.isChecked() !== checked) await page.locator('.el-checkbox').filter({ has: input }).click()
}
async function select(page, name, option) {
  await page.locator('.el-select').filter({ has: page.getByRole('combobox', { name, exact: true }) }).locator('.el-select__wrapper').click()
  await page.getByRole('option', { name: option, exact: true }).click()
}
async function open(page) {
  await page.goto(url)
  await page.locator('.tool-title').filter({ hasText: 'JSON' }).click()
  await page.getByRole('textbox', { name: 'JSON 输入', exact: true }).waitFor()
}
async function waitText(page, label, expected) {
  await page.waitForFunction(({ label, expected }) => [...document.querySelectorAll('.cm-content')].find(node => node.getAttribute('aria-label') === label)?.textContent.includes(expected), { label, expected })
}
