    await page.getByRole('button', { name: '展开代码', exact: true }).click()
    assert.equal(await page.locator('.cm-foldPlaceholder').count(), 0)
    await page.getByRole('button', { name: '查找与替换', exact: true }).click()
    await page.locator('.cm-search').waitFor()
    await page.locator('.cm-search [name="search"]').fill('old')
